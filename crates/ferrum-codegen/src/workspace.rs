//! The output workspace: the crates that hold the generated functions, the root crate that
//! registers them in the function table, and the root manifest with the generated profile.
//!
//! Functions are split in address order into crates of `functions_per_crate`; each of those
//! depends only on `ferrum-runtime` and lists its functions, and the root crate depends on all of
//! them and registers their lists. Calls between crates go through the table, because a crate
//! cannot depend on another that depends on it.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::{fs, io};

use crate::error::Error;
use crate::program::{PRELUDE, Program};

#[cfg(test)]
mod tests;

/// The first line of every generated file.
const GENERATED: &str = "Generated by ferrum-codegen. Do not edit: regenerate instead.";

/// The inner attributes of every generated crate: no `unsafe`, and no lints over code that no one
/// writes by hand.
const CRATE_ATTRIBUTES: &str =
    "#![forbid(unsafe_code)]\n#![allow(unused, clippy::all, missing_docs)]\n";

/// The generated profile, for `[profile.dev]` and `[profile.release]`. A port that builds the
/// output as a dependency repeats it, since Cargo reads profiles only from the root manifest of
/// the workspace it builds.
pub const PROFILE: &str =
    "debug = false\nincremental = false\noverflow-checks = false\ncodegen-units = 256\n";

/// The default of `functions_per_crate`, measured with `ferrum-scale`. From about 500 functions
/// up, checking a crate takes twice as long or more when its size doubles, so small crates check
/// fastest, down to about 100 functions, where the fixed cost of each crate takes over.
pub const DEFAULT_FUNCTIONS_PER_CRATE: usize = 100;

/// How [`Program::workspace`] lays out the output.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Layout {
    /// The name of the root crate, such as `naruto-ppc`. The crates that hold the functions are
    /// `<name>-NNN`.
    pub name: String,
    /// How many functions each `<name>-NNN` crate holds, in address order. The last one holds the
    /// rest. [`DEFAULT_FUNCTIONS_PER_CRATE`] is the measured default.
    pub functions_per_crate: usize,
    /// The directory of `ferrum-runtime`, which every crate depends on.
    pub runtime: PathBuf,
}

/// One file of the output workspace.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OutputFile {
    /// Its path from the root of the workspace, with `/` between components.
    pub path: String,
    /// Its content.
    pub text: String,
}

impl Program<'_> {
    /// Every file of the output workspace: the root manifest, then the root crate, then the
    /// `<name>-NNN` crates in address order.
    ///
    /// Opcodes without `emit_*` are counted over every crate, as [`Program::generate`] does. A
    /// layout that cannot be written, such as an invalid crate name, is an error.
    pub fn workspace(&self, layout: &Layout) -> Result<Vec<OutputFile>, Error> {
        check_name(&layout.name)?;
        self.check_hooks()?;
        self.check_dispatch()?;
        if layout.functions_per_crate == 0 {
            return Err(invalid("functions_per_crate is zero"));
        }
        let runtime = layout
            .runtime
            .to_str()
            .ok_or_else(|| invalid("the path of ferrum-runtime is not valid UTF-8"))?;
        let entries: Vec<u32> = self.entries().collect();
        if entries.is_empty() {
            return Err(invalid("there is no function to generate"));
        }
        let chunks: Vec<&[u32]> = entries.chunks(layout.functions_per_crate).collect();
        let names = Names::new(&layout.name, chunks.len());

        let mut files = vec![
            root_manifest(&names, runtime),
            root_crate_manifest(&names),
            root_crate_lib(&names),
            self.table(&names),
            OutputFile {
                path: format!("{}/src/imports.rs", names.root),
                text: format!("// {GENERATED}\n\n{}", self.imports_file()),
            },
            OutputFile {
                path: format!("{}/src/hooks.rs", names.root),
                text: format!("// {GENERATED}\n\n{}", self.hooks_file()),
            },
        ];
        let mut missing = BTreeMap::new();
        for (index, chunk) in chunks.iter().enumerate() {
            let (first, last) = (chunk[0], chunk[chunk.len() - 1]);
            match self.generate_part(first..=last) {
                Ok(text) => {
                    files.push(part_manifest(&names, index));
                    let listed: Vec<(u32, String)> = chunk
                        .iter()
                        .filter_map(|&entry| self.table_path(entry).map(|path| (entry, path)))
                        .collect();
                    files.push(part_lib(&names, index, chunk, &listed, &text));
                }
                Err(Error::MissingEmit { counts }) => {
                    for (name, count) in counts {
                        *missing.entry(name).or_insert(0) += count;
                    }
                }
                Err(other) => return Err(other),
            }
        }
        if missing.is_empty() {
            Ok(files)
        } else {
            Err(Error::MissingEmit { counts: missing })
        }
    }

    /// The root crate's `table.rs`: the range of the entries, and the registration of every
    /// crate's list of functions and of the import thunks.
    fn table(&self, names: &Names) -> OutputFile {
        let thunks = self.imports().iter().filter_map(|import| import.thunk);
        let entries: Vec<u32> = self.entries().chain(thunks).collect();
        let first = entries.iter().copied().min().unwrap_or(self.code().base());
        let last = entries.iter().copied().max().unwrap_or(first);
        // From the first entry to the last, inclusive: under 2^30 words.
        let words = ((last - first) / 4 + 1) as usize;
        let mut text = format!("// {GENERATED}\n\n");
        text.push_str("use ferrum_runtime::{Error, FnTable, GuestFn};\n\n");
        text.push_str("/// The first address the table covers, the lowest entry.\n");
        text.push_str(&format!("pub const BASE: u32 = {first:#010x};\n\n"));
        text.push_str("/// The words from `BASE` to the highest entry, one table entry each.\n");
        text.push_str(&format!("pub const WORDS: usize = {words};\n\n"));
        text.push_str("/// The functions of every crate, as entry address and function.\n");
        text.push_str(&format!(
            "static LISTS: [&[(u32, GuestFn)]; {}] = [\n",
            names.parts + 1
        ));
        for index in 0..names.parts {
            text.push_str(&format!("    &{}::FUNCTIONS,\n", names.part_lib(index)));
        }
        text.push_str("    &crate::imports::THUNKS,\n");
        text.push_str("];\n\n");
        text.push_str(
            "/// Registers every recompiled function in `table`, for indirect calls and for calls\n\
             /// between crates.\n\
             pub fn register(table: &mut FnTable) -> Result<(), Error> {\n    \
             table.register_entries(BASE, WORDS, &LISTS)\n}\n",
        );
        OutputFile {
            path: format!("{}/src/table.rs", names.root),
            text,
        }
    }
}

/// Writes `files` under `dir`, creating directories as needed, and returns how many it wrote.
///
/// A file that already holds the same content is left alone, so that Cargo still sees it as
/// fresh. Nothing is deleted.
pub fn write_workspace(dir: &Path, files: &[OutputFile]) -> io::Result<usize> {
    let mut written = 0;
    for file in files {
        let path = file
            .path
            .split('/')
            .fold(dir.to_path_buf(), |p, c| p.join(c));
        if fs::read(&path).is_ok_and(|old| old == file.text.as_bytes()) {
            continue;
        }
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&path, &file.text)?;
        written += 1;
    }
    Ok(written)
}

/// The names of the crates of one workspace.
struct Names {
    /// The root crate, which is also the name of the workspace.
    root: String,
    /// How many `<root>-NNN` crates there are.
    parts: usize,
    /// How many digits their numbers have.
    width: usize,
}

impl Names {
    fn new(root: &str, parts: usize) -> Self {
        let width = (parts - 1).to_string().len().max(3);
        Self {
            root: root.to_owned(),
            parts,
            width,
        }
    }

    /// The package name of crate `index`.
    fn part(&self, index: usize) -> String {
        format!("{}-{index:0width$}", self.root, width = self.width)
    }

    /// The name by which Rust code refers to crate `index`.
    fn part_lib(&self, index: usize) -> String {
        self.part(index).replace('-', "_")
    }
}

/// The root `Cargo.toml`: the members, the shared package fields, the runtime dependency and the
/// generated profile.
fn root_manifest(names: &Names, runtime: &str) -> OutputFile {
    let mut text = format!("# {GENERATED}\n\n[workspace]\nmembers = [\n");
    text.push_str(&format!("    {},\n", toml_string(&names.root)));
    for index in 0..names.parts {
        text.push_str(&format!("    {},\n", toml_string(&names.part(index))));
    }
    text.push_str("]\nresolver = \"3\"\n\n");
    text.push_str(
        "[workspace.package]\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n",
    );
    text.push_str(&format!(
        "[workspace.dependencies]\nferrum-runtime = {{ path = {} }}\n\n",
        toml_string(runtime)
    ));
    text.push_str(
        "# The generated profile. Cargo reads profiles only from the root manifest of the\n\
         # workspace it builds.\n",
    );
    text.push_str(&format!(
        "[profile.dev]\n{PROFILE}\n[profile.release]\n{PROFILE}"
    ));
    OutputFile {
        path: "Cargo.toml".to_owned(),
        text,
    }
}

/// The `[package]` table of a generated crate.
fn package(name: &str) -> String {
    format!(
        "# {GENERATED}\n\n[package]\nname = {}\nversion.workspace = true\n\
         edition.workspace = true\npublish.workspace = true\n\n",
        toml_string(name)
    )
}

/// The root crate's manifest: it depends on the runtime and on every `<root>-NNN` crate.
fn root_crate_manifest(names: &Names) -> OutputFile {
    let mut text = package(&names.root);
    text.push_str("[dependencies]\nferrum-runtime.workspace = true\n");
    for index in 0..names.parts {
        let part = names.part(index);
        let path = toml_string(&format!("../{part}"));
        text.push_str(&format!("{part} = {{ path = {path} }}\n"));
    }
    OutputFile {
        path: format!("{}/Cargo.toml", names.root),
        text,
    }
}

/// The root crate's `lib.rs`.
fn root_crate_lib(names: &Names) -> OutputFile {
    let text = format!(
        "// {GENERATED}\n\n\
         //! The recompiled guest code of `{}`: registers the functions of its {} crates and the\n\
         //! import thunks in a `FnTable`; `imports::load` fills the import slots, and `hooks`\n\
         //! lists the hooks the port installs.\n\n\
         {CRATE_ATTRIBUTES}\n\
         pub mod hooks;\n\
         pub mod imports;\n\
         mod table;\n\n\
         pub use table::{{register, BASE, WORDS}};\n",
        names.root, names.parts
    );
    OutputFile {
        path: format!("{}/src/lib.rs", names.root),
        text,
    }
}

/// The manifest of crate `index`: it depends on the runtime only.
fn part_manifest(names: &Names, index: usize) -> OutputFile {
    let mut text = package(&names.part(index));
    text.push_str("[dependencies]\nferrum-runtime.workspace = true\n");
    OutputFile {
        path: format!("{}/Cargo.toml", names.part(index)),
        text,
    }
}

/// The `lib.rs` of crate `index`, which holds the functions from the first of `entries` to the
/// last: the list of the functions the table holds, by entry and Rust path, then the functions.
fn part_lib(
    names: &Names,
    index: usize,
    entries: &[u32],
    listed: &[(u32, String)],
    functions: &str,
) -> OutputFile {
    let (first, last) = (entries[0], entries[entries.len() - 1]);
    let mut text = format!(
        "// {GENERATED}\n\n\
         //! Crate {} of {} of `{}`: the guest functions from {first:#010x} to {last:#010x}.\n\n\
         {CRATE_ATTRIBUTES}\n\
         {PRELUDE}use ferrum_runtime::GuestFn;\n\n",
        index + 1,
        names.parts,
        names.root
    );
    text.push_str("/// The functions of this crate, as entry address and function.\n");
    text.push_str(&format!(
        "pub static FUNCTIONS: [(u32, GuestFn); {}] = [\n",
        listed.len()
    ));
    for (entry, path) in listed {
        text.push_str(&format!("    ({entry:#010x}, {path}),\n"));
    }
    text.push_str("];\n\n");
    text.push_str(functions);
    OutputFile {
        path: format!("{}/src/lib.rs", names.part(index)),
        text,
    }
}

/// Checks that `name` can name a crate: an ASCII letter, then ASCII letters, digits, `-` and `_`.
fn check_name(name: &str) -> Result<(), Error> {
    let mut chars = name.chars();
    let valid = chars.next().is_some_and(|c| c.is_ascii_alphabetic())
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if valid {
        Ok(())
    } else {
        Err(invalid(format!("{name:?} is not a valid crate name")))
    }
}

fn invalid(why: impl Into<String>) -> Error {
    Error::InvalidLayout { why: why.into() }
}

/// A TOML basic string holding `value`.
fn toml_string(value: &str) -> String {
    let mut text = String::from("\"");
    for c in value.chars() {
        match c {
            '"' => text.push_str("\\\""),
            '\\' => text.push_str("\\\\"),
            c if c.is_control() => text.push_str(&format!("\\u{:04X}", u32::from(c))),
            c => text.push(c),
        }
    }
    text.push('"');
    text
}
